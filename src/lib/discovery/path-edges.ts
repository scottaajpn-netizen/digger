import type { DiscoveryPath, DiscoveryPathNode } from "../types";

// These are provenance descriptions, NOT calibrated reliability percentages
// or acoustic/music-similarity estimates.
export type PathEdgeRelation =
  | "track-similarity" | "radio-association"
  | "artist-anchor" | "artist-similarity" | "artist-catalogue-track"
  | "seed-tag-context" | "tag-artist-context"
  | "release-membership" | "release-label" | "label-release"
  | "release-artist-credit" | "artist-release"
  | "release-context" | "context-release" | "tag-radio-context"
  | "unclassified";

export type PathEdgeSupport = "provider-association" | "catalogue-fact" | "contextual" | "unclassified";
export type PathEdge = {
  index: number;
  from: Pick<DiscoveryPathNode, "kind" | "name" | "id">;
  to: Pick<DiscoveryPathNode, "kind" | "name" | "id">;
  relation: PathEdgeRelation;
  support: PathEdgeSupport;
};

// A semantic map of edges generated by src/lib/discovery/paths.ts.
// Even a "catalogue-fact" means only that this catalogue lists the link:
// it does NOT mean the recordings sound alike. These mappings are conservative
// when a source does not supply enough detail to prove a particular edge.
export function inspectPathEdges(path: DiscoveryPath | undefined, origin?: string): PathEdge[] {
  if (!path?.nodes?.length) return [];
  const result: PathEdge[] = [];
  for (let index=0; index<path.nodes.length-1; index++) {
    const from=path.nodes[index], to=path.nodes[index+1];
    let relation: PathEdgeRelation = "unclassified";
    let support: PathEdgeSupport = "unclassified";
    const select=(r:PathEdgeRelation,s:PathEdgeSupport)=>{
      relation=r;support=s;
    };

    if (path.source==="lastfm") {
      if (from.kind==="track" && to.kind==="track" && path.evidence==="listening" &&
          ["lastfm-similar","lastfm-deep"].includes(origin || "")) {
        select("track-similarity","provider-association");
      } else if (from.kind==="track" && to.kind==="artist") {
        // An anchor can come from MusicBrainz credit matching or a fallback;
        // the path alone cannot certify an explicit recording credit.
        select("artist-anchor","contextual");
      } else if (from.kind==="artist" && to.kind==="artist") {
        select("artist-similarity","provider-association");
      } else if (from.kind==="artist" && to.kind==="track") {
        select("artist-catalogue-track","catalogue-fact");
      } else if (from.kind==="track" && to.kind==="context") {
        select("seed-tag-context","contextual");
      } else if (from.kind==="context" && to.kind==="artist") {
        select("tag-artist-context","provider-association");
      }
    } else if (path.source==="discogs") {
      if (from.kind==="track" && to.kind==="release") {
        select("release-membership","catalogue-fact");
      } else if (from.kind==="release" && to.kind==="track") {
        select("release-membership","catalogue-fact");
      } else if (from.kind==="release" && to.kind==="label") {
        select("release-label","catalogue-fact");
      } else if (from.kind==="label" && to.kind==="release") {
        select("label-release","catalogue-fact");
      } else if (from.kind==="release" && to.kind==="artist") {
        select("release-artist-credit","catalogue-fact");
      } else if (from.kind==="artist" && to.kind==="release") {
        select("artist-release","catalogue-fact");
      } else if (from.kind==="track" && to.kind==="artist") {
        select("artist-anchor","contextual");
      } else if (from.kind==="release" && to.kind==="context") {
        select("release-context","contextual");
      } else if (from.kind==="context" && to.kind==="release") {
        select("context-release","contextual");
      }
    } else if (path.source==="listenbrainz") {
      if (from.kind==="track" && to.kind==="track" && path.evidence==="listening") {
        select("radio-association","provider-association");
      } else if (from.kind==="track" && to.kind==="context") {
        select("seed-tag-context","contextual");
      } else if (from.kind==="context" && to.kind==="track") {
        select("tag-radio-context","contextual");
      }
    }

    result.push({
      index,
      from:{kind:from.kind,name:from.name,id:from.id},
      to:{kind:to.kind,name:to.name,id:to.id},
      relation,support,
    });
  }
  return result;
}
